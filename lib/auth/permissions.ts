import { USER_ROLES, UserRole } from "../constants";

export const PERMISSIONS = {
  VIEW_PARCELS: "VIEW_PARCELS",
  UPLOAD_SOURCE: "UPLOAD_SOURCE",
  OPEN_REVIEW: "OPEN_REVIEW",
  MODIFY_PROPOSAL: "MODIFY_PROPOSAL",
  APPROVE_PROPOSAL: "APPROVE_PROPOSAL",
  REJECT_PROPOSAL: "REJECT_PROPOSAL",
  RUN_OCR: "RUN_OCR",
  EXPORT_REPORTS: "EXPORT_REPORTS",
  ADMIN_RESET_DEMO: "ADMIN_RESET_DEMO",
} as const;

export type Permission = (typeof PERMISSIONS)[keyof typeof PERMISSIONS];

const ROLE_PERMISSIONS_MAP: Record<UserRole, Permission[]> = {
  [USER_ROLES.ADMIN]: [
    PERMISSIONS.VIEW_PARCELS,
    PERMISSIONS.UPLOAD_SOURCE,
    PERMISSIONS.OPEN_REVIEW,
    PERMISSIONS.MODIFY_PROPOSAL,
    PERMISSIONS.APPROVE_PROPOSAL,
    PERMISSIONS.REJECT_PROPOSAL,
    PERMISSIONS.RUN_OCR,
    PERMISSIONS.EXPORT_REPORTS,
    PERMISSIONS.ADMIN_RESET_DEMO,
  ],
  [USER_ROLES.REVIEW_OFFICER]: [
    PERMISSIONS.VIEW_PARCELS,
    PERMISSIONS.UPLOAD_SOURCE,
    PERMISSIONS.OPEN_REVIEW,
    PERMISSIONS.MODIFY_PROPOSAL,
    PERMISSIONS.APPROVE_PROPOSAL,
    PERMISSIONS.REJECT_PROPOSAL,
    PERMISSIONS.RUN_OCR,
    PERMISSIONS.EXPORT_REPORTS,
  ],
  [USER_ROLES.FIELD_OFFICER]: [
    PERMISSIONS.VIEW_PARCELS,
    PERMISSIONS.UPLOAD_SOURCE,
    PERMISSIONS.RUN_OCR,
    PERMISSIONS.EXPORT_REPORTS,
  ],
  [USER_ROLES.VIEWER]: [PERMISSIONS.VIEW_PARCELS],
};

export function hasPermission(role: UserRole, permission: Permission): boolean {
  const allowedPermissions = ROLE_PERMISSIONS_MAP[role] || [];
  return allowedPermissions.includes(permission);
}
